# Emit the BMP character table used by the external scanner. PowerShell's
# unbraced-variable tokenizer examines UTF-16 chars with Char.IsLetterOrDigit.
# Regenerate with: pwsh -NoProfile -File scripts/generate-unicode.ps1 > src/variable_chars.h
[CmdletBinding()]
param([switch] $JavaScript)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if ($JavaScript) {
    # Regex engines may carry a newer Unicode database than the pinned .NET
    # runtime. Emit the runtime's exact classes instead of using \p{L}/\p{Nd}.
    function Get-CharacterClass([bool] $LetterOnly) {
        $ranges = [Text.StringBuilder]::new()
        $start = -1
        for ($codepoint = 0; $codepoint -le 0x10000; $codepoint++) {
            $matches = $false
            if ($codepoint -lt 0x10000) {
                $matches = if ($LetterOnly) {
                    [char]::IsLetter([char]$codepoint)
                } else {
                    [char]::IsLetterOrDigit([char]$codepoint)
                }
            }
            if ($matches -and $start -eq -1) {
                $start = $codepoint
            } elseif (-not $matches -and $start -ne -1) {
                $end = $codepoint - 1
                [void] $ranges.Append(('\\u{0:X4}' -f $start))
                if ($end -ne $start) {
                    [void] $ranges.Append(('-\\u{0:X4}' -f $end))
                }
                $start = -1
            }
        }
        return '[' + $ranges.ToString() + ']'
    }

    "// Generated by scripts/generate-unicode.ps1 with PowerShell $($PSVersionTable.PSVersion)."
    "// .NET runtime: $([Environment]::Version); BMP Char.IsLetter/IsLetterOrDigit."
    'module.exports = {'
    "  LETTER_CHARACTER_CLASS: '$(Get-CharacterClass $true)',"
    "  LETTER_OR_DIGIT_CHARACTER_CLASS: '$(Get-CharacterClass $false)',"
    '};'
    exit
}

"// Generated by scripts/generate-unicode.ps1 with PowerShell $($PSVersionTable.PSVersion)."
"// .NET runtime: $([Environment]::Version); classification: Char.IsLetterOrDigit."
'// Unbraced variable names use UTF-16 chars; supplementary scalars are excluded.'
'#ifndef TREE_SITTER_POWERSHELL_VARIABLE_CHARS_H_'
'#define TREE_SITTER_POWERSHELL_VARIABLE_CHARS_H_'
'#include <stdint.h>'
'static const uint16_t VARIABLE_CHARACTER_RANGES[][2] = {'
$start = -1
for ($codepoint = 0; $codepoint -le 0x10000; $codepoint++) {
    $matches = $codepoint -lt 0x10000 -and [char]::IsLetterOrDigit([char]$codepoint)
    if ($matches -and $start -eq -1) {
        $start = $codepoint
    } elseif (-not $matches -and $start -ne -1) {
        '  {{0x{0:X4}, 0x{1:X4}}},' -f $start, ($codepoint - 1)
        $start = -1
    }
}
'};'
'#endif'
